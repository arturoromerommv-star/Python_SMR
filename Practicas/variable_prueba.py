#Python no tiene ningún comando para declarar una variable.
#Una variable se crea en el momento en que le asignas un valor por primera vez.
print("############################################################################")
j = 5
y = "Jhon" 
print(j)
print(y)

#No es necesario declarar variables con ningún tipo en particular e incluso pueden cambiar de tipo una vez configuradas.
print("############################################################################")
x = 4
x = "Sally"
print(x)

#Podemos especificar también el dato de la variable
print("############################################################################")
n = str(3)
k = int(3)
l = float(3)
print(n)
print(type(k)) #También se puede tener el tipo de la variable con type() 
print(l)
